"""Generate the corrected-label retraining notebooks from the historical fair-comparison notebooks.

Every change is an explicit, exact-match replacement (or an inserted/removed cell) listed below,
so the derived notebooks differ from the originals only where the retraining protocol requires:
deduplicated input, a label-mode switch (corrected | original), the episode-aware split, the
output bias recomputed with the historical rule (logit of training prevalence), new Drive paths,
and guards for subsets that no longer exist. Models, features, windows, training and evaluation
code are unchanged; the training notebooks still pin utility commit 2262b53.

Usage (from the repository root): python3 code/python/scripts/derive_corrected_notebooks.py
"""
import copy
import json
from pathlib import Path

NB = Path('code/python/notebook')


def src(text):
    lines = text.split('\n')
    return [line + '\n' for line in lines[:-1]] + ([lines[-1]] if lines[-1] else [])


def cell(kind, text):
    c = dict(cell_type=kind, metadata={}, source=src(text))
    if kind == 'code':
        c.update(execution_count=None, outputs=[])
    return c


def derive(original, target, edits, title):
    nb = json.loads((NB / original).read_text())
    cells = nb['cells']
    for c in cells:
        if c['cell_type'] == 'code':
            c['outputs'], c['execution_count'] = [], None
    new_cells = []
    for index, c in enumerate(cells):
        action = edits.get(index, [])
        if action == 'delete':
            continue
        if isinstance(action, dict):                       # replace whole cell
            c = copy.deepcopy(c)
            c['source'] = src(action['source'])
            action = action.get('then', [])
        text = ''.join(c['source'])
        for old, new in action if isinstance(action, list) else []:
            if old is None:
                continue
            count = text.count(old)
            assert count == 1, f'{original} cell {index}: expected one match, found {count}: {old[:80]!r}'
            text = text.replace(old, new)
        c = copy.deepcopy(c)
        c['source'] = src(text)
        new_cells.append(c)
        for extra in edits.get(f'after_{index}', []):
            new_cells.append(extra)
    new_cells = edits.get('prepend', []) + new_cells + edits.get('append', [])
    nb['cells'] = new_cells
    nb['metadata'].pop('widgets', None)
    nb['metadata'].setdefault('colab', {})['name'] = target
    (NB / target).write_text(json.dumps(nb, indent=1, ensure_ascii=False) + '\n')
    print('wrote', NB / target, f'({len(new_cells)} cells) — {title}')


